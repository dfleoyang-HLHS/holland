# 檢查：8 端 × 6 型都有說明、沒有重複、沒有空白
assert list(ENTRIES) == [p[0] for p in POLES]
texts = []
for pole, row in ENTRIES.items():
    assert list(row) == [t[0] for t in TYPES], pole
    for code, text in row.items():
        assert text.strip() and text.endswith("。"), (pole, code)
        texts.append(text)
assert len(texts) == 48 and len(set(texts)) == 48

